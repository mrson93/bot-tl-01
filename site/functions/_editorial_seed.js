export function editorialBody(article){
  const links=(RELATED[article.slug]||[]).map(slug=>EDITORIAL_ARTICLES.find(item=>item.slug===slug)).filter(Boolean);
  if(!links.length)return article.body_markdown;
  return `${article.body_markdown}\n\n## Leia também\n\n${links.map(item=>`- [${item.title}](https://canaltabarato.com.br/blog/${item.slug})`).join('\n')}`;
}

async function ensureMigrationTable(env){
  await env.DB.prepare('CREATE TABLE IF NOT EXISTS site_migrations (id TEXT PRIMARY KEY,applied_at INTEGER NOT NULL)').run();
}

export async function ensureEditorialSeed(env,now=Math.floor(Date.now()/1000)){
  await ensureMigrationTable(env);
  const applied=await env.DB.prepare('SELECT id FROM site_migrations WHERE id=?').bind(EDITORIAL_SEED_ID).first();
  let created=0,productsCreated=0;
  if(!applied){
    const statements=EDITORIAL_ARTICLES.map((article,index)=>env.DB.prepare(`INSERT OR IGNORE INTO blog_posts
      (id,slug,title,excerpt,body_markdown,cover_image_url,category,status,meta_title,meta_description,published_at,created_at,updated_at)
      VALUES(?,?,?,?,?,?,?,'published',?,?,?,?,?)`).bind(article.id,article.slug,article.title,article.excerpt,editorialBody(article),article.cover_image_url,article.category,article.meta_title,article.meta_description,now-index,now-index,now-index));
    statements.push(env.DB.prepare('INSERT INTO site_migrations(id,applied_at) VALUES(?,?)').bind(EDITORIAL_SEED_ID,now));
    await env.DB.batch(statements);created=EDITORIAL_ARTICLES.length;
  }
  await ensureBlogProducts(env);
  const modelsApplied=await env.DB.prepare('SELECT id FROM site_migrations WHERE id=?').bind(EDITORIAL_MODELS_SEED_ID).first();
  if(!modelsApplied){
    const statements=EDITORIAL_MODELS.map(model=>env.DB.prepare(`INSERT OR IGNORE INTO blog_post_products
      (post_id,id,name,brand,summary,image_url,affiliate_url,price_label,specs_json,position)
      VALUES(?,?,?,?,?,?,'',NULL,?,?)`).bind(model.post_id,model.id,model.name,model.brand,model.summary,model.image_url,JSON.stringify(model.specs),model.position));
    statements.push(env.DB.prepare('INSERT INTO site_migrations(id,applied_at) VALUES(?,?)').bind(EDITORIAL_MODELS_SEED_ID,now));
    await env.DB.batch(statements);productsCreated=EDITORIAL_MODELS.length;
  }
  const coversApplied=await env.DB.prepare('SELECT id FROM site_migrations WHERE id=?').bind(EDITORIAL_COVERS_SEED_ID).first();
  let coversUpdated=0;
  if(!coversApplied){
    const ids=EDITORIAL_ARTICLES.map(article=>article.id),placeholders=ids.map(()=>'?').join(',');
    const result=await env.DB.prepare(`UPDATE blog_posts SET cover_image_url=?,updated_at=? WHERE id IN (${placeholders}) AND (cover_image_url IS NULL OR cover_image_url='')`).bind(CELLULAR_GUIDES_COVER,now,...ids).run();
    coversUpdated=Number(result.meta?.changes)||0;
    await env.DB.prepare('INSERT INTO site_migrations(id,applied_at) VALUES(?,?)').bind(EDITORIAL_COVERS_SEED_ID,now).run();
  }
  const imagesApplied=await env.DB.prepare('SELECT id FROM site_migrations WHERE id=?').bind(EDITORIAL_MODEL_IMAGES_SEED_ID).first();
  let imagesUpdated=0;
  if(!imagesApplied){
    for(const model of EDITORIAL_MODELS){
      const result=await env.DB.prepare(`UPDATE blog_post_products SET image_url=? WHERE post_id=? AND id=? AND (image_url IS NULL OR image_url='')`).bind(model.image_url,model.post_id,model.id).run();
      imagesUpdated+=Number(result.meta?.changes)||0;
    }
    await env.DB.prepare('INSERT INTO site_migrations(id,applied_at) VALUES(?,?)').bind(EDITORIAL_MODEL_IMAGES_SEED_ID,now).run();
  }
  return {created,products_created:productsCreated,covers_updated:coversUpdated,images_updated:imagesUpdated};
}
